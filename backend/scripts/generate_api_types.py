"""Generate TypeScript API types from the FastAPI OpenAPI schema.

Usage (from backend/):
    APP_SECRET_KEY=<40+ chars> python scripts/generate_api_types.py \
        ../frontend/src/shared/api/types.ts

Regenerate whenever the contract schemas change. The output is a plain type
module (no runtime code) that the frontend can import for type-checking.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any

from app.main import create_app

HEADER = """/** AUTO-GENERATED by backend/scripts/generate_api_types.py — do not edit. */
/* eslint-disable */

"""


def _ts_type(schema: dict[str, Any], schemas: dict[str, Any]) -> str:
    if "$ref" in schema:
        name = schema["$ref"].rsplit("/", 1)[-1]
        return name

    if "enum" in schema:
        return " | ".join(json.dumps(value, ensure_ascii=False) for value in schema["enum"])

    if "anyOf" in schema or "oneOf" in schema:
        options = schema.get("anyOf") or schema.get("oneOf")
        parts = [_ts_type(option, schemas) for option in options]
        return " | ".join(parts)

    kind = schema.get("type")
    if kind == "array":
        item = schema.get("items", {})
        inner = _ts_type(item, schemas)
        return f"({inner})[]" if "|" in inner else f"{inner}[]"

    if kind == "object":
        props = schema.get("properties")
        if not props:
            additional = schema.get("additionalProperties")
            if isinstance(additional, dict):
                return f"Record<string, {_ts_type(additional, schemas)}>"
            return "Record<string, unknown>"
        lines = []
        required = set(schema.get("required", []))
        for key, value in props.items():
            optional = "" if key in required else "?"
            doc = value.get("description")
            if doc:
                lines.append(f"  /** {doc} */")
            lines.append(f"  {json.dumps(key)}{optional}: {_ts_type(value, schemas)};")
        return "{\n" + "\n".join(lines) + "\n}"

    if kind == "integer" or kind == "number":
        return "number"
    if kind == "boolean":
        return "boolean"
    if kind == "string":
        return "string"
    if kind == "null":
        return "null"

    return "unknown"


def generate(output_path: Path) -> None:
    spec = create_app().openapi()
    schemas = spec.get("components", {}).get("schemas", {})

    declarations = []
    for name, schema in schemas.items():
        description = schema.get("description")
        doc = f"/** {description} */\n" if description else ""
        ts_type = _ts_type(schema, schemas)
        if ts_type.startswith("{"):
            declarations.append(f"{doc}export interface {name} {ts_type}")
        else:
            declarations.append(f"{doc}export type {name} = {ts_type};")

    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(HEADER + "\n\n".join(declarations) + "\n", encoding="utf-8")
    print(f"Generated {output_path} ({len(schemas)} types)")


def main() -> None:
    if len(sys.argv) != 2:
        print("usage: generate_api_types.py <output.ts>", file=sys.stderr)
        raise SystemExit(2)
    generate(Path(sys.argv[1]))


if __name__ == "__main__":
    main()
