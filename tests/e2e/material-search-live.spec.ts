import { expect, test } from '@playwright/test'

test('素材主题检索可补选已使用素材，刷新保留并移除', async ({ page }) => {
  test.skip(process.env.MATERIAL_SEARCH_E2E !== '1', '需要独立测试库及预先构建的固定样例')
  await page.goto('/#/login')
  await page.getByLabel('账号').fill('admin')
  await page.getByLabel('密码').fill('correct-password')
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await expect(page).toHaveURL(/dashboard/)
  await page.goto('/#/creation')
  await page.getByLabel('创作主题').fill('动力电池循环利用')
  await page.getByLabel('范围').selectOption('all')
  await page.getByRole('button', { name: '检索', exact: true }).click()
  const candidate = page.getByRole('listitem').filter({ hasText: '新能源汽车电池回收' })
  await expect(candidate).toContainText('相关度')
  await expect(candidate).toContainText('来源')
  await candidate.getByRole('checkbox').check()
  await expect(page.getByRole('heading', { name: '已选择素材（1）' })).toBeVisible()
  await page.reload()
  await expect(page.getByLabel('创作主题')).toHaveValue('动力电池循环利用')
  await expect(page.getByRole('heading', { name: '已选择素材（1）' })).toBeVisible()
  await page.getByRole('button', { name: '移除' }).click()
  await expect(page.getByRole('heading', { name: '已选择素材（0）' })).toBeVisible()
  await expect(page.getByRole('button', { name: '提交创作' })).toBeDisabled()
})
