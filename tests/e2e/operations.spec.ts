import { test, expect } from '@playwright/test'
import type { Page } from '@playwright/test'

test.skip(!process.env.E2E_BACKEND_URL,'需要隔离测试API')
async function csrf(page:Page){return {'X-CSRF-Token':await page.evaluate(()=>decodeURIComponent(document.cookie.split('; ').find(s=>s.startsWith('wetchat_csrf='))!.split('=')[1]))}}

test('工作台对账、通知、报表导出及平台设置持久化（隔离数据库）',async({page})=>{
  test.setTimeout(90_000)
  await page.goto('/#/login')
  await page.getByRole('textbox',{name:'账号',exact:true}).fill('admin')
  await page.getByLabel('密码',{exact:true}).fill('correct-password')
  await page.getByRole('button',{name:'登录',exact:true}).click()
  await expect(page).toHaveURL(/#\/dashboard/)
  await expect(page.getByRole('heading',{name:'待办事项',exact:true})).toBeVisible()
  const headers=await csrf(page)
  const title=`=SUM(1,2) [fixture] 阶段8审核 ${Date.now()}`
  const article=await(await page.request.post('/api/v1/articles',{headers,data:{title,body_markdown:'阶段8确定性验证正文'}})).json()
  expect((await page.request.post(`/api/v1/articles/${article.article_id}/submit-review`,{headers,data:{base_revision_id:article.current_revision_id}})).ok()).toBeTruthy()
  await page.getByRole('button',{name:'刷新工作台',exact:true}).click()
  const todo=page.locator('section.ops-card').filter({has:page.getByRole('heading',{name:'待办事项',exact:true})})
  await expect(todo.getByRole('link',{name:title,exact:true})).toHaveAttribute('href',`#/content/articles/${article.article_id}`)
  await page.getByRole('button',{name:'获取最新通知',exact:true}).click()
  await expect(page.getByRole('button',{name:'标记已读'}).first()).toBeVisible()
  await page.getByRole('button',{name:'标记已读'}).first().click()
  const review=await page.request.post(`/api/v1/article-revisions/${article.current_revision_id}/reviews`,{headers,data:{action:'approve',checklist:Object.fromEntries(['title','content','facts','citations','image_copyright','account_compliance','layout'].map(k=>[k,'pass']))}})
  expect(review.status()).toBe(201)
  await page.goto('/#/analytics?kind=reviews')
  await expect(page.getByRole('heading',{name:'报表明细',exact:true})).toBeVisible()
  await expect(page.getByRole('link',{name:title,exact:true})).toBeVisible()
  const download=page.waitForEvent('download')
  await page.getByRole('button',{name:'导出当前筛选全部CSV',exact:true}).click()
  const file=await download;expect(file.suggestedFilename()).toBe('reviews.csv')
  await page.reload()
  await expect(page.getByRole('combobox',{name:'数据类型',exact:true})).toHaveValue('reviews')
  await page.goto('/#/settings?tab=platform')
  const old=await(await page.request.get('/api/v1/settings/platform')).json()
  await page.getByLabel('平台名称',{exact:true}).fill('[fixture] 阶段8智媒助手')
  await page.getByRole('button',{name:'保存平台设置',exact:true}).click()
  await expect(page.getByText('平台设置已保存，刷新后仍然有效。')).toBeVisible()
  await page.reload()
  await expect(page.getByLabel('平台名称',{exact:true})).toHaveValue('[fixture] 阶段8智媒助手')
  await page.getByRole('button',{name:'用户管理',exact:true}).click()
  await expect(page.getByRole('heading',{name:'用户管理',exact:true})).toBeVisible()
  await page.getByRole('button',{name:'角色权限',exact:true}).click()
  await page.getByRole('combobox',{name:'选择角色',exact:true}).selectOption({label:'editor'})
  await expect(page.getByRole('checkbox',{name:'article:write',exact:true})).toBeChecked()
  await page.getByRole('button',{name:'第三方接口',exact:true}).click()
  await expect(page.getByRole('heading',{name:'第三方接口与运行配置',exact:true})).toBeVisible()
  await page.getByRole('button',{name:'操作日志',exact:true}).click()
  await expect(page.getByRole('cell',{name:/settings\.platform\.update/}).first()).toBeVisible()
  await page.getByRole('button',{name:'任务监控',exact:true}).click()
  await expect(page.getByRole('heading',{name:'异步任务监控',exact:true})).toBeVisible()
  for(const module of ['采集管理','智能创作','内容管理','素材库','账号管理','数据统计分析','系统设置','工作台']){
    await page.getByRole('navigation',{name:'主导航'}).getByRole('button',{name:module,exact:true}).click()
    if(module==='智能创作') await expect(page.getByRole('navigation',{name:'创作页面'})).toBeVisible()
    else if(module==='工作台') await expect(page.getByRole('heading',{name:'待办事项',exact:true})).toBeVisible()
    else await expect(page.getByRole('heading',{name:module==='账号管理'?'公众号账号管理':module,exact:true})).toBeVisible()
    await expect(page.getByText('页面不存在',{exact:true})).toHaveCount(0)
    await expect(page.getByText('无访问权限',{exact:true})).toHaveCount(0)
  }
  await expect(page.getByText('正在加载运营概览…',{exact:true})).toHaveCount(0)
  await expect(page.getByText('正在加载通知…',{exact:true})).toHaveCount(0)
  await page.screenshot({path:'test-results/operations-desktop.png',fullPage:true})
  await page.setViewportSize({width:390,height:844})
  await page.goto('/#/analytics?kind=accounts')
  await expect(page.getByRole('heading',{name:'报表明细',exact:true})).toBeVisible()
  expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBeLessThanOrEqual(390)
  await page.screenshot({path:'test-results/operations-mobile.png',fullPage:true})
  const current=await(await page.request.get('/api/v1/settings/platform')).json()
  expect((await page.request.put('/api/v1/settings/platform',{headers,data:{name:old.name,description:old.description,brand_mark:old.brand_mark,timezone:old.timezone,version:current.version}})).ok()).toBeTruthy()
})
