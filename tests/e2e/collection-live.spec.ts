import { expect,test } from '@playwright/test'

test('真实 API 和数据库完成主题搜索到素材闭环（外部服务 fixture）',async({page})=>{
  test.skip(!process.env.COLLECTION_E2E_FIXTURE,'需要独立数据库和外部服务 fixture 后端')
  await page.goto('/#/login')
  await page.getByLabel('账号').fill('admin')
  await page.getByLabel('密码').fill('correct-password')
  await page.getByRole('button',{name:'登录',exact:true}).click()
  await expect(page).toHaveURL(/dashboard/)
  const cookies=await page.context().cookies()
  const headers={'X-CSRF-Token':cookies.find(c=>c.name==='wetchat_csrf')!.value}
  const suffix=Date.now()
  const search=await page.request.post('/api/v1/search-configs',{headers,data:{name:`浏览器搜索-${suffix}`,provider:'tavily',credential_ref:'E2E_SEARCH_KEY'}})
  expect(search.status()).toBe(201)
  const searchId=(await search.json()).id
  const model=await page.request.post('/api/v1/model-configs',{headers,data:{name:`浏览器模型-${suffix}`,provider:'fixture',purpose:'analysis',endpoint:'https://example.com/v1/chat/completions',model_name:'fixture'}})
  expect(model.status()).toBe(201)
  const modelId=(await model.json()).id
  await page.goto('/#/collection?view=tasks')
  await page.getByLabel('任务名称').fill(`浏览器主题日报-${suffix}`)
  await page.getByLabel('采集模式').selectOption('topic_search')
  await page.getByLabel('主题',{exact:true}).fill(`人工智能 ${suffix}`)
  await page.locator('select[name="search"]').selectOption(searchId)
  await page.getByLabel('LLM 素材分析').check()
  await page.locator('select[name="model"]').selectOption(modelId)
  await page.getByLabel('自动入库',{exact:true}).check()
  await page.getByRole('button',{name:'新建任务',exact:true}).click()
  const row=page.locator('tbody tr').filter({hasText:`浏览器主题日报-${suffix}`})
  const accepted=page.waitForResponse(r=>r.url().endsWith('/run')&&r.request().method()==='POST')
  await row.getByRole('button',{name:'立即执行'}).click()
  const job=await(await accepted).json()
  const drained=await page.request.post(`${process.env.E2E_BACKEND_URL}/__test__/drain/${job.async_job_id}`,{headers})
  expect((await drained.json()).status).toBe('succeeded')
  await page.goto(`/#/collection?view=results&run_id=${job.resource_id}`)
  await expect(page.getByRole('cell',{name:'人工智能行业新闻',exact:true})).toBeVisible()
  await expect(page.getByRole('cell',{name:'materialized',exact:true})).toBeVisible()
  await page.getByRole('button',{name:'分析详情'}).click()
  await expect(page.getByText('人工智能行业新闻的测试摘要',{exact:true}).first()).toBeVisible()
  await expect(page.getByText(/元数据版本：/).first()).toBeVisible()
  const results=await(await page.request.get(`/api/v1/collection/results?run_id=${job.resource_id}`)).json()
  const materialId=results.items[0].material_id
  const material=await(await page.request.get(`/api/v1/materials/${materialId}`)).json()
  expect((await page.request.patch(`/api/v1/materials/${materialId}`,{headers,data:{summary:'分析页面打开后的人工摘要',base_metadata_version:material.metadata_version}})).status()).toBe(200)
  await page.getByRole('button',{name:'采用摘要'}).first().click()
  await expect(page.getByText('素材已归档或元数据版本已变化',{exact:true})).toBeVisible()
  await page.getByRole('button',{name:'查看素材'}).click()
  await expect(page.getByRole('heading',{name:'人工智能行业新闻',exact:true})).toBeVisible()
  await page.reload()
  await expect(page.getByRole('heading',{name:'人工智能行业新闻',exact:true})).toBeVisible()
  await page.screenshot({path:'test-results/collection-live.png',fullPage:true})
})
