import { expect, test } from '@playwright/test'
import type { Page } from '@playwright/test'

test.skip(!process.env.E2E_BACKEND_URL, '需要独立测试 API 和确定性微信 fixture')

async function csrf(page: Page) { return { 'X-CSRF-Token': await page.evaluate(() => decodeURIComponent(document.cookie.split('; ').find(item => item.startsWith('wetchat_csrf='))!.split('=')[1])) } }

test('直连接入、同步、显式确认、未知结果核对及失败重试（确定性微信 fixture）', async ({ page }) => {
  test.setTimeout(60_000)
  await page.goto('/#/login')
  await page.getByRole('textbox', { name: '账号', exact: true }).fill('admin')
  await page.getByLabel('密码', { exact: true }).fill('correct-password')
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await expect(page).toHaveURL(/#\/dashboard/)
  await page.getByRole('navigation', { name: '主导航' }).getByRole('button', { name: '账号管理', exact: true }).click()
  const existing = (await (await page.request.get('/api/v1/wechat-accounts')).json()).items.find((item: { app_id: string }) => item.app_id === 'wx0123456789abcdef')
  if (existing) {
    await page.goto(`/#/accounts?account_id=${existing.id}`)
    await page.getByLabel('重新接入 AppSecret', { exact: true }).fill('fixture-only-not-a-real-appsecret')
    await page.getByRole('button', { name: '校验并重新接入', exact: true }).click()
    await expect(page.getByText('新凭据校验成功。')).toBeVisible()
    await page.getByRole('textbox', { name: '显示名称', exact: true }).fill('[确定性fixture] 自有公众号')
    await page.getByRole('checkbox', { name: '已核实微信后台发布接口权限', exact: true }).check()
    await page.getByRole('button', { name: '保存账号配置', exact: true }).click()
  } else {
    await page.getByText('接入公众号', { exact: true }).click()
    await page.getByRole('textbox', { name: '公众号名称', exact: true }).fill('[确定性fixture] 自有公众号')
    await page.getByRole('textbox', { name: 'AppID', exact: true }).fill('wx0123456789abcdef')
    await page.getByLabel('AppSecret', { exact: true }).fill('fixture-only-not-a-real-appsecret')
    await page.getByRole('checkbox', { name: '我已在微信后台核实该账号具有发布接口权限' }).check()
    await page.getByRole('button', { name: '校验凭据并接入', exact: true }).click()
  }
  await expect(page.getByRole('heading', { name: '[确定性fixture] 自有公众号', exact: true })).toBeVisible()
  await expect(page.getByText(/已配置，不回显/)).toBeVisible()
  await page.getByRole('button', { name: '设为默认账号', exact: true }).click()
  await expect(page.getByText(/已设置默认账号/)).toBeVisible()
  const syncResponse = page.waitForResponse(response => response.url().endsWith('/sync') && response.request().method() === 'POST')
  await page.getByRole('button', { name: '同步永久图文', exact: true }).click()
  const sync = await (await syncResponse).json()
  const headers = await csrf(page)
  expect((await page.request.post(`/api/v1/__test__/drain/${sync.async_job_id}`, { headers })).ok()).toBeTruthy()
  await expect(page.getByText(/已完成 · 新增 1/)).toBeVisible({ timeout: 10_000 })
  const accountId = new URLSearchParams(page.url().split('?')[1]).get('account_id')
  expect(accountId).toBeTruthy()
  const cover = await (await page.request.post('/api/v1/__test__/cover', { headers })).json()
  const articleResponse = await page.request.post('/api/v1/articles', { headers, data: { title: '[fixture] 公众号发布验证', body_markdown: '# 确定性测试\n\n此内容仅用于本地测试。', cover_object_id: cover.id } })
  expect(articleResponse.status()).toBe(201)
  const article = await articleResponse.json()
  await page.goto(`/#/content/articles/${article.article_id}`)
  await page.getByRole('button', { name: '提交审核', exact: true }).click()
  const review = page.locator('.review-form')
  for (const name of ['标题准确', '正文正确', '事实与数据', '引用来源', '公众号规范', '排版', '图片版权与适用性']) await review.getByRole('combobox', { name, exact: true }).selectOption('pass')
  await review.getByRole('button', { name: '提交审核结论', exact: true }).click()
  const panel = page.getByRole('region', { name: '发布管理' })
  await page.getByText('有接口发布权限的账号：自动发布管理', { exact: true }).click()
  await panel.getByRole('combobox', { name: '目标公众号', exact: true }).selectOption(accountId!)
  const orderResponse = page.waitForResponse(response => response.url().endsWith('/publish-orders') && response.request().method() === 'POST')
  await panel.getByRole('button', { name: '创建待确认发布单', exact: true }).click()
  const order = await (await orderResponse).json()
  await expect(panel.getByRole('button', { name: '确认按上述账号、版本和时间发布', exact: true })).toBeVisible()
  expect(await (await page.request.get(`/api/v1/publish-orders/${order.id}/attempts`)).json()).toHaveLength(0)
  await page.request.post('/api/v1/__test__/mode', { headers, data: { timeout_next: true } })
  const confirmation = page.waitForResponse(response => response.url().endsWith('/confirm'))
  await panel.getByRole('button', { name: '确认按上述账号、版本和时间发布', exact: true }).click()
  const confirmed = await (await confirmation).json()
  await page.request.post(`/api/v1/__test__/drain/${confirmed.async_job_id}`, { headers })
  await panel.getByRole('button', { name: '刷新发布状态', exact: true }).click()
  await expect(panel.getByRole('heading', { name: '结果未知，须核对', exact: true })).toBeVisible()
  await expect(panel.getByRole('button', { name: '重试已确认失败的发布单', exact: true })).toHaveCount(0)
  await panel.getByRole('combobox', { name: '核对方式', exact: true }).selectOption('not_published')
  await panel.getByRole('textbox', { name: '核对依据', exact: true }).fill('确定性fixture：已核对，模拟平台未发布')
  await panel.getByRole('button', { name: '提交结果核对', exact: true }).click()
  await expect(panel.getByRole('heading', { name: '发布失败', exact: true })).toBeVisible()
  const retryResponse = page.waitForResponse(response => response.url().endsWith('/retry'))
  await panel.getByRole('button', { name: '重试已确认失败的发布单', exact: true }).click()
  const retry = await (await retryResponse).json()
  await page.request.post(`/api/v1/__test__/drain/${retry.async_job_id}`, { headers })
  await panel.getByRole('button', { name: '刷新发布状态', exact: true }).click()
  await expect(panel.getByRole('heading', { name: '已发布', exact: true })).toBeVisible()
  const attempts = await (await page.request.get(`/api/v1/publish-orders/${order.id}/attempts`)).json()
  expect(attempts.map((item: { status: string }) => item.status)).toEqual(['failed', 'succeeded'])
  await page.screenshot({ path: 'test-results/wechat-publish-desktop.png', fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390)
  await page.screenshot({ path: 'test-results/wechat-publish-mobile.png', fullPage: true })
})

test('个人号审核后同步私有草稿，再人工登记发布（确定性微信 fixture）', async ({ page }) => {
  await page.goto('/#/login')
  await page.getByRole('textbox', { name: '账号', exact: true }).fill('admin')
  await page.getByLabel('密码', { exact: true }).fill('correct-password')
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await expect(page).toHaveURL(/#\/dashboard/)
  const headers = await csrf(page)
  const list = (await (await page.request.get('/api/v1/wechat-accounts')).json()).items
  let account = list.find((item: { app_id: string }) => item.app_id === 'wxfedcba9876543210')
  if (!account) {
    const response = await page.request.post('/api/v1/wechat-accounts', { headers, data: { name: '[fixture] 个人订阅号', app_id: 'wxfedcba9876543210', app_secret: 'fixture-only-not-a-real-appsecret', publish_permission_confirmed: false } })
    expect(response.status()).toBe(201)
    account = await response.json()
  }
  expect((await page.request.patch(`/api/v1/wechat-accounts/${account.id}`, { headers, data: { publish_permission_confirmed: false } })).ok()).toBeTruthy()
  const cover = await (await page.request.post('/api/v1/__test__/cover', { headers })).json()
  const article = await (await page.request.post('/api/v1/articles', { headers, data: { title: '[fixture] 私有草稿交付', body_markdown: '# 草稿验证\n\n这是确定性测试内容。', cover_object_id: cover.id } })).json()
  await page.goto(`/#/content/articles/${article.article_id}`)
  await page.getByRole('button', { name: '提交审核', exact: true }).click()
  const review = page.locator('.review-form')
  for (const name of ['标题准确', '正文正确', '事实与数据', '引用来源', '公众号规范', '排版', '图片版权与适用性']) await review.getByRole('combobox', { name, exact: true }).selectOption('pass')
  await review.getByRole('button', { name: '提交审核结论', exact: true }).click()
  const panel = page.getByRole('region', { name: '微信草稿箱' })
  await panel.getByRole('combobox', { name: '草稿目标公众号', exact: true }).selectOption(account.id)
  await panel.getByRole('checkbox', { name: /我已核对当前审核版本/ }).check()
  const response = page.waitForResponse(value => value.url().endsWith('/wechat-draft-deliveries') && value.request().method() === 'POST')
  await panel.getByRole('button', { name: '确认同步到微信草稿箱', exact: true }).click()
  const delivery = await (await response).json()
  expect((await page.request.post(`/api/v1/__test__/drain/${delivery.async_job_id}`, { headers })).ok()).toBeTruthy()
  await panel.getByRole('button', { name: '刷新草稿状态', exact: true }).click()
  await expect(panel.getByRole('heading', { name: '草稿已同步，待微信后台手动发布', exact: true })).toBeVisible()
  expect((await (await page.request.get(`/api/v1/articles/${article.article_id}`)).json()).status).toBe('approved')
  await page.reload()
  await panel.getByRole('button', { name: /草稿已同步，待微信后台手动发布/ }).click()
  await expect(panel.getByRole('link', { name: '打开微信公众平台', exact: true })).toHaveAttribute('href', 'https://mp.weixin.qq.com/')
  await panel.getByRole('textbox', { name: '微信文章链接', exact: true }).fill('https://mp.weixin.qq.com/s/fixture-manual-evidence')
  await panel.getByRole('textbox', { name: '人工发布说明', exact: true }).fill('确定性fixture：模拟已在微信后台发布')
  await panel.getByRole('checkbox', { name: /我已在微信后台发布/ }).check()
  await panel.getByRole('button', { name: '登记已手动发布', exact: true }).click()
  await expect(panel.getByRole('heading', { name: '已发布（人工登记）', exact: true })).toBeVisible()
  const recorded = await (await page.request.get(`/api/v1/wechat-draft-deliveries/${delivery.id}`)).json()
  expect(recorded.publication_source).toBe('operator')
  expect((await (await page.request.get(`/api/v1/publish-orders?article_id=${article.article_id}`)).json()).total).toBe(0)
  await page.screenshot({ path: 'test-results/wechat-draft-desktop.png', fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390)
  await page.screenshot({ path: 'test-results/wechat-draft-mobile.png', fullPage: true })
})
