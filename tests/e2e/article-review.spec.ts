import { expect, test } from '@playwright/test'

test.skip(!process.env.E2E_BACKEND_URL, '需要独立测试 API')

test('人工文章退回、修改、复审通过；旧批准不能放行新版本', async ({ page }) => {
  await page.goto('/#/login')
  await page.getByRole('textbox', { name: '账号', exact: true }).fill('admin')
  await page.getByLabel('密码', { exact: true }).fill('correct-password')
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await expect(page).toHaveURL(/#\/dashboard/)
  await page.getByRole('navigation', { name: '主导航' }).getByRole('button', { name: '内容管理', exact: true }).click()
  await page.getByRole('button', { name: '新建文章', exact: true }).click()
  const title = `浏览器复审样例 ${Date.now()}`
  await page.getByRole('textbox', { name: '文章标题', exact: true }).fill(title)
  await page.getByRole('textbox', { name: 'Markdown 正文', exact: true }).fill('# 中文正文\n\n原始事实来源待补充。')
  await page.getByRole('textbox', { name: '作者', exact: true }).fill('测试编辑')
  await page.getByRole('combobox', { name: '模板', exact: true }).selectOption('news')
  await page.getByRole('button', { name: '保存新版本', exact: true }).click()
  await expect(page).toHaveURL(/#\/content\/articles\//)
  await expect(page.getByText(/当前 v1/)).toBeVisible()
  await expect(page.getByRole('combobox', { name: '模板', exact: true })).toHaveValue('news')
  await expect(page.frameLocator('iframe[title="手机预览"]').getByRole('heading', { name: '中文正文' })).toBeVisible()
  await page.getByRole('button', { name: '提交审核', exact: true }).click()
  await expect(page.getByRole('heading', { name: '审核当前 v1', exact: true })).toBeVisible()
  await page.getByRole('combobox', { name: '审核结论', exact: true }).selectOption('return')
  await expect(page.getByRole('button', { name: '提交审核结论', exact: true })).toBeDisabled()
  await page.getByRole('textbox', { name: '审核意见', exact: true }).fill('补充事实依据后复审')
  await page.getByRole('button', { name: '提交审核结论', exact: true }).click()
  await expect(page.getByText('退回修改 · 当前 v1')).toBeVisible()
  await page.getByRole('textbox', { name: 'Markdown 正文', exact: true }).fill('# 中文正文\n\n已核对并补充事实依据。')
  page.once('dialog', dialog => dialog.dismiss())
  await page.getByRole('button', { name: '返回列表', exact: true }).click()
  await expect(page.getByRole('textbox', { name: 'Markdown 正文', exact: true })).toHaveValue('# 中文正文\n\n已核对并补充事实依据。')
  await page.getByRole('button', { name: '保存新版本', exact: true }).click()
  await expect(page.getByText(/当前 v2/)).toBeVisible()
  await page.getByRole('button', { name: '提交审核', exact: true }).click()
  const form = page.locator('.review-form')
  for (const label of ['标题准确', '正文正确', '事实与数据', '引用来源', '公众号规范', '排版']) {
    await form.getByRole('combobox', { name: label, exact: true }).selectOption('pass')
  }
  await form.getByRole('combobox', { name: '图片版权与适用性', exact: true }).selectOption('not_applicable')
  await form.getByRole('combobox', { name: '审核结论', exact: true }).selectOption('approve')
  await form.getByRole('button', { name: '提交审核结论', exact: true }).click()
  await expect(page.getByText('审核通过／待发布 · 当前 v2')).toBeVisible()
  await page.reload()
  await expect(page.getByRole('textbox', { name: 'Markdown 正文', exact: true })).toHaveValue('# 中文正文\n\n已核对并补充事实依据。')
  await page.getByRole('button', { name: '查看 v1', exact: true }).click()
  await expect(page.getByText('补充事实依据后复审', { exact: true })).toBeVisible()
  await expect(page.getByRole('textbox', { name: 'Markdown 正文', exact: true })).toHaveValue('# 中文正文\n\n原始事实来源待补充。')
  await page.getByRole('button', { name: '返回当前版本', exact: true }).click()
  await page.getByRole('textbox', { name: 'Markdown 正文', exact: true }).fill('审核通过后再次编辑的新正文')
  await page.getByRole('button', { name: '保存新版本', exact: true }).click()
  await expect(page.getByText('草稿 · 当前 v3')).toBeVisible()
  await expect(page.frameLocator('iframe[title="手机预览"]').getByText('审核通过后再次编辑的新正文')).toBeVisible()
  await page.screenshot({ path: 'test-results/article-review-desktop.png', fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390)
  await page.screenshot({ path: 'test-results/article-review-mobile.png', fullPage: true })
})
